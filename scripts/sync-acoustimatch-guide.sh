#!/bin/sh
# Copy the AcoustiMatch user guide from the app repo into the site.
# The app repo's docs/user-guide.html is the source of truth; don't edit the
# copies. Re-run this whenever the guide changes.
#
# Writes:
#   src/data/acoustimatch-guide.html        the scoped <style> and <article>,
#                                           rendered by /software/acoustimatch/guide
#   public/images/acoustimatch/guide/       the guide's screenshots
#   public/downloads/acoustimatch/AcoustiMatch-User-Guide.pdf
#                                           (only if the PDF has been built)
#
# Usage: scripts/sync-acoustimatch-guide.sh [path/to/acoustimatch]
set -eu

REPO="${1:-$HOME/projects/dsp/acoustimatch}"
SRC="$REPO/docs/user-guide.html"
IMAGES="$REPO/docs/images"
PDF="$REPO/build/AcoustiMatch User Guide.pdf"
SITE="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$SITE/src/data/acoustimatch-guide.html"
IMG_DEST="$SITE/public/images/acoustimatch/guide"
IMG_URL="/images/acoustimatch/guide/"

[ -f "$SRC" ] || { echo "missing $SRC" >&2; exit 1; }
[ -d "$IMAGES" ] || { echo "missing $IMAGES" >&2; exit 1; }

mkdir -p "$(dirname "$OUT")"
{
  echo "<!-- Generated by scripts/sync-acoustimatch-guide.sh from acoustimatch/docs/user-guide.html. Don't edit. -->"
  # The first <style> block is the guide's scoped .am-guide styles; the
  # second is for the standalone page and PDF only, so it's left out.
  awk '/^<style>/ { n++ } n == 1 { print } n == 1 && /^<\/style>/ { exit }' "$SRC"
  sed -n '/^<article class="am-guide">/,/^<\/article>/p' "$SRC"
} | sed "s|src=\"images/|src=\"$IMG_URL|g" > "$OUT"

grep -q '<article class="am-guide">' "$OUT" || { echo "article not found in $SRC" >&2; exit 1; }
grep -q '</style>' "$OUT" || { echo "style block not found in $SRC" >&2; exit 1; }
if grep -q 'src="images/' "$OUT"; then echo "unrewritten image path in $OUT" >&2; exit 1; fi

rm -rf "$IMG_DEST"
mkdir -p "$IMG_DEST"
cp "$IMAGES"/*.png "$IMG_DEST/"

for img in $(grep -o "src=\"$IMG_URL[^\"]*\"" "$OUT" | sed "s|src=\"$IMG_URL||; s|\"||" | sort -u); do
  [ -f "$IMG_DEST/$img" ] || { echo "guide references missing image $img" >&2; exit 1; }
done

if [ -f "$PDF" ]; then
  cp "$PDF" "$SITE/public/downloads/acoustimatch/AcoustiMatch-User-Guide.pdf"
  echo "Copied the PDF"
else
  echo "No PDF at $PDF; run scripts/build-user-guide.sh in the app repo to include it" >&2
fi

echo "Synced the user guide into $OUT"
